#!/usr/bin/env python3
"""A slash command that FAILS writes its error as a user record wrapped in <local-command-stderr>, the twin of
<local-command-stdout>: a custom command, skill or MCP prompt that cannot expand, or a forked command that errors.
The CLI reads that record as the command's output, never as a prompt. The event model knew only the stdout tag, so
the error fell through every wrapper skip to a plain user atom authored 'human': a turn of its own that never ended,
a chat bubble holding the raw tags, and a segment the judges' never-skip floor took for the user's ask. Both readers
(the transcript parse and the live stream) now read it as the command's output atom, which ends the command's turn.
Synthetic transcript only: placeholder UUIDs, the notes-api demo, invented text."""
import datetime
import json
import os
import tempfile
import time
import unittest
from romp_load import load_source

HERE = os.path.dirname(os.path.realpath(__file__))
BIN = os.path.join(os.path.dirname(HERE), "bin")
# Hermetic state BEFORE the loads — they resolve their state root at import time, and only
# pytest runs conftest's floor (a bare unittest or script run otherwise writes REAL state).
os.environ["XDG_STATE_HOME"] = tempfile.mkdtemp()
os.environ.pop("ROMP_STATE_DIR", None)  # a live kernel's export outranks the XDG floor
em = load_source("romp_event_model_cmd_stderr", os.path.join(BIN, "romp-event-model"))

SID = "11111111-2222-3333-4444-555555555555"
ERR = "Error: Error during compaction: Error: Not enough messages to compact."
STDERR = "<local-command-stderr>%s</local-command-stderr>" % ERR
BUILTIN = "<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args></command-args>"
CUSTOM = ("<command-message>deploy-check</command-message>\n<command-name>/deploy-check</command-name>\n"
          "<command-args>api</command-args>")


def _iso(ep):
    return datetime.datetime.fromtimestamp(ep, tz=datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def _recs(wrapper, output=STDERR):
    """A prompt and its reply, then a slash command whose output record (promptId p2, no isMeta) is `output`."""
    now = int(time.time())
    return [
        {"type": "user", "timestamp": _iso(now - 300), "uuid": "u1", "parentUuid": None, "promptId": "p1",
         "message": {"role": "user", "content": "please add a health route to notes-api"}},
        {"type": "assistant", "timestamp": _iso(now - 290), "uuid": "a1", "parentUuid": "u1",
         "message": {"role": "assistant", "content": [{"type": "text", "text": "Added GET /health."}],
                     "stop_reason": "end_turn"}},
        {"type": "user", "timestamp": _iso(now - 60), "uuid": "c0", "parentUuid": "a1", "promptId": "p2", "isMeta": True,
         "message": {"role": "user", "content": "<local-command-caveat>Caveat: the messages below were generated by "
                                                "the user while running local commands.</local-command-caveat>"}},
        {"type": "user", "timestamp": _iso(now - 60), "uuid": "c1", "parentUuid": "c0", "promptId": "p2",
         "message": {"role": "user", "content": wrapper}},
        {"type": "user", "timestamp": _iso(now - 59), "uuid": "c2", "parentUuid": "c1", "promptId": "p2",
         "message": {"role": "user", "content": output}},
    ]


def _parse(recs):
    td = tempfile.mkdtemp()
    p = os.path.join(td, SID + ".jsonl")
    with open(p, "w") as f:
        f.write("\n".join(json.dumps(r) for r in recs) + "\n")
    return em.parse_session(p, rompuuid=SID, name="web", dir="/TESTDIR",
                            candidate_files=[p], states=None, postal_log=[], now=int(time.time()))


def _text(a):
    return em._text_of(em._content(a.get("message"))) or ""


class FailedCommandTranscript(unittest.TestCase):
    def _check(self, wrapper, name):
        sess = _parse(_recs(wrapper))
        turns = sess["turns"]
        self.assertEqual(len(turns), 2, "the error stays inside the command's own turn, not a turn of its own")
        cmd_turn = turns[-1]
        self.assertTrue(cmd_turn["ended"], "a failed command's turn is over once its error lands")
        self.assertEqual([a["uuid"] for a in cmd_turn["atoms"]], ["c1", "c2"])
        inv, out = cmd_turn["atoms"]
        self.assertEqual(inv.get("command"), name)
        self.assertEqual(out["type"], "assistant", "the error is the command's OUTPUT, like stdout")
        self.assertIs(out.get("command"), True)
        self.assertEqual(out["message"]["stop_reason"], "end_turn")
        self.assertEqual(_text(out), ERR, "the output atom carries the error without the wrapper tags")
        for t in turns:
            for a in t["atoms"]:
                self.assertNotIn("local-command-stderr", _text(a), "no atom shows the raw tags")
        humans = [a["uuid"] for t in turns for a in t["atoms"]
                  if a["type"] == "user" and a.get("author") == "human" and not a.get("command")]
        self.assertEqual(humans, ["u1"], "the only human prompt is the one the user typed")

    def test_builtin_command_error(self):
        self._check(BUILTIN, "/compact")

    def test_custom_command_error(self):
        self._check(CUSTOM, "/deploy-check")

    def test_the_wrapper_family_includes_stderr(self):
        # the kernel's comment-thread screens and the human-input reader key on this regex
        self.assertTrue(em.CMD_WRAP_RE.match(STDERR))
        self.assertEqual(em.local_command_output(STDERR).group(1), ERR)
        self.assertEqual(em.local_command_output("<local-command-stdout>ok</local-command-stdout>").group(1), "ok")
        self.assertIsNone(em.local_command_output("about " + STDERR), "prose that quotes the tag is not output")

    def test_a_restored_output_atom_hydrates_its_error_text(self):
        """A pre-cut atom restored from a stored document is lazy: hydrate rebuilds its body from the record by
        its kind. The stderr output atom is kind "o", and the "o" body must read the stderr tag too, or the
        restored atom comes back empty."""
        recs = _recs(CUSTOM)
        out = _parse(recs)["turns"][-1]["atoms"][-1]
        self.assertEqual(em._atom_kind(out), "o")
        lazy = {"type": "assistant", "uuid": "c2", "command": True, "lazy": {"k": "o"}}
        em._hydrate_one(lazy, recs[-1])
        self.assertEqual(lazy["message"]["content"], [{"type": "text", "text": ERR}])
        self.assertEqual(lazy["message"]["stop_reason"], "end_turn")


class JudgeReadsNoAsk(unittest.TestCase):
    def test_no_human_floor_segment_and_no_worked_command(self):
        jd = load_source("romp_judge_cmd_stderr", os.path.join(BIN, "romp-judge"))
        sess = _parse(_recs(CUSTOM))
        segs = [sg for t in sess["turns"] for sg in em.segments(t)]
        floor = [sg.get("trigger") for sg in segs if jd._seg_human(sg) and not jd._seg_command(sg)]
        self.assertEqual(floor, ["u1"], "the error output is no human ask on the never-skip floor")
        cmd = [sg for sg in segs if jd._seg_command(sg)]
        self.assertEqual(len(cmd), 1)
        self.assertFalse(jd._seg_command_worked(cmd[0]), "a command that failed put the model to no work: no card")


class _TextBlock:
    def __init__(self, text):
        self.text = text


class _UserMessage:
    def __init__(self, content, uuid="c2"):
        self.content, self.uuid = content, uuid


_TextBlock.__name__ = "TextBlock"
_UserMessage.__name__ = "UserMessage"   # msg_to_atom matches the SDK's types by name


class FailedCommandLiveStream(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.sb = load_source("romp_sdk_backend_cmd_stderr", os.path.join(BIN, "romp_sdk_backend.py"))

    def test_streamed_stderr_is_a_turn_ending_output_atom(self):
        a = self.sb.msg_to_atom(_UserMessage([_TextBlock(STDERR)]), SID, "f", 5)
        self.assertEqual(a["type"], "assistant", "the live atom gets the transcript parse's classification")
        self.assertIs(a.get("command"), True)
        self.assertEqual(a["message"]["stop_reason"], "end_turn")
        self.assertEqual(a["message"]["content"], [{"type": "text", "text": ERR}])

    def test_the_live_wrapper_twins_match_the_file_adapter_s(self):
        # sdk_backend keeps its own copies of the wrapper regexes (msg_to_atom predates its event-model binding), so
        # this pin is what keeps the two readers widening together
        for live, disk in (("_CMD_WRAP_RE", "CMD_WRAP_RE"), ("_LOCAL_STDOUT_RE", "LOCAL_STDOUT_RE"),
                           ("_LOCAL_STDERR_RE", "LOCAL_STDERR_RE")):
            self.assertEqual(getattr(self.sb, live).pattern, getattr(em, disk).pattern, live)


if __name__ == "__main__":
    unittest.main()
