//! Python's string semantics where they differ from Rust's: `str.isspace` (and so `strip()` and a str regex's `\s`)
//! counts U+001C..U+001F as whitespace, which Rust's `char::is_whitespace` does not, `len()` counts code points,
//! not UTF-8 bytes (the boundary atom is 79 code points and 82 bytes), and `str.upper()` follows Python's Unicode
//! version, not the toolchain's (`upper`, from the generated `pystr_tables.rs`).

use crate::pystr_tables::{UPPER, UPPER_FULL};

/// `ch.isspace()`, and what `\s` matches in a Python str regex (both are `Py_UNICODE_ISSPACE`): Unicode White_Space
/// plus the four information separators U+001C..U+001F (bidirectional class B or S). The unit test checks every
/// code point against the list Python wrote into the layer-1 fixture.
pub fn is_space(c: char) -> bool {
    c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c)
}

/// `s.strip()`.
pub fn strip(s: &str) -> &str {
    s.trim_matches(is_space)
}

/// `len(s)`: code points.
pub fn len(s: &str) -> usize {
    s.chars().count()
}

/// `s[start:]` in whitespace terms: the rest of `s` after its leading `\s*`.
pub fn skip_space(s: &str) -> &str {
    s.trim_start_matches(is_space)
}

/// `s.upper()`: Python's full uppercase mapping (`ß` gives `SS`), read from Python's own tables (`pystr_tables.rs`,
/// generated by `python3 tools/rust-spike/dump_layer6.py --tables`; `tests/layer6_edge.rs` checks every code point
/// against the table Python writes into the layer-6 fixture). Rust's `char::to_uppercase` follows the toolchain's
/// Unicode version (18.0 on Rust 1.100), where Python 3.12's is 15.0: the two disagree on 76 code points, the case
/// pairs Unicode 16 to 18 added (`ɤ` uppercases to `Ɤ` in Rust and stays `ɤ` in Python). Python's `upper()` takes no
/// context, so it maps one code point at a time.
pub fn upper(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        let u = c as u32;
        if let Ok(i) = UPPER_FULL.binary_search_by(|&(k, _)| k.cmp(&u)) {
            out.push_str(UPPER_FULL[i].1);
            continue;
        }
        let i = match UPPER.binary_search_by(|&(first, ..)| first.cmp(&u)) {
            Ok(i) => i,
            Err(0) => {
                out.push(c);
                continue;
            }
            Err(i) => i - 1,
        };
        let (first, last, step, delta) = UPPER[i];
        if u > last || (step > 0 && (u - first) % step != 0) || (step == 0 && u != first) {
            out.push(c);
        } else {
            out.push(char::from_u32(u.wrapping_add_signed(delta)).expect("an uppercase mapping is a code point"));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn separators_are_space_in_python_but_not_in_rust() {
        let s = "\u{1c}\u{1f} x \u{1d}";
        assert_eq!(s.trim(), s, "Rust's trim keeps U+001C..U+001F");
        assert_eq!(strip(s), "x");
        assert_eq!(strip("\u{a0}\u{2003}x\u{3000}\u{85}"), "x");
        assert_eq!(strip("\u{200b}x"), "\u{200b}x", "a zero-width space is not whitespace in either");
    }

    #[test]
    fn len_counts_code_points() {
        let boundary = "Recap: limit \u{2192} 3, the na\u{ef}ve cache is gone; the search suite passes, once again.";
        assert_eq!(len(boundary), 79);
        assert_eq!(boundary.len(), 82);
        assert_eq!(len("\u{1f600}"), 1);
    }

    #[test]
    fn upper_is_pythons_full_mapping_at_its_unicode_version() {
        assert_eq!(upper("stra\u{df}e \u{149}"), "STRASSE \u{2bc}N");
        assert_eq!(upper("\u{1c6}ob"), "\u{1c4}OB", "the titlecase digraph's uppercase, not its titlecase");
        // case pairs Unicode 16 to 18 added: Rust's own tables map them, Python 3.12's (Unicode 15) do not
        for c in ['\u{264}', '\u{a7cd}', '\u{10d70}'] {
            assert_ne!(c.to_uppercase().collect::<String>(), c.to_string(), "{c:?}");
            assert_eq!(upper(&c.to_string()), c.to_string(), "{c:?}");
        }
    }
}
